/**
 * Установленное на экран «Домой» приложение на iOS.
 *
 * Отличать этот режим приходится потому, что в нём нет ни адресной строки, ни
 * менеджера загрузок: скачанный файл человеку просто некуда деть, и считать
 * такую «загрузку» сохранённой копией — значит соврать про сохранность данных.
 *
 * Свойство navigator.standalone нестандартное и есть только в Safari на iOS —
 * ровно там, где оно и нужно.
 */
export function isIosStandalone(): boolean {
  return (navigator as Navigator & { standalone?: boolean }).standalone === true
}
