import type { MouseEvent } from 'react'

/**
 * Оставляет фокус там, где он был, при тапе по кнопке-переключателю.
 *
 * iOS убирает клавиатуру, как только фокус уходит из поля ввода: вьюпорт
 * перестраивается, и форма в шторке заметно дёргается. Отмена mousedown
 * не даёт фокусу перейти на кнопку — click при этом срабатывает как обычно,
 * а переход по Tab не затрагивается.
 */
export function keepFocus(event: MouseEvent): void {
  event.preventDefault()
}
